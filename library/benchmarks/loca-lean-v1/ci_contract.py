#!/usr/bin/env python3
"""CI contract: one canary, deterministic regeneration, oracle/NOP/mutants."""
from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from materializer import materialize, output_path, reject_committed_corpora
from templates import mutants, nop, oracle
from verifier import verify


def snapshot(root: Path) -> dict[str, str]:
    return {
        str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def main() -> None:
    reject_committed_corpora()
    forbidden = ("tasks", "vendor", "source_configs")
    tracked = [
        path
        for suffix in forbidden
        for prefix in ("library/benchmarks/loca-bench", "library/benchmarks/loca-lean-v1")
        for path in subprocess.check_output(["git", "ls-files", f"{prefix}/{suffix}"], text=True).splitlines()
    ]
    if tracked:
        raise AssertionError(f"generated/vendor LOCA corpus is tracked: {tracked[:3]}")
    target = output_path()
    materialize(target)
    first = snapshot(target)
    materialize(target)
    second = snapshot(target)
    if first != second:
        raise AssertionError("canary regeneration changed generated bytes")
    rewards = target / "tests" / "rewards"
    nop(target, target / "agent_workspace")
    nop_result = verify(target, reward_dir=rewards / "nop")
    if nop_result["reward"] != 0.0 or (rewards / "nop" / "reward.txt").read_text().strip() != "0.0":
        raise AssertionError("NOP candidate was accepted")
    materialize(target)
    oracle(target, target / "agent_workspace")
    oracle_result = verify(target, reward_dir=rewards / "oracle")
    if oracle_result["reward"] != 1.0 or (rewards / "oracle" / "reward.txt").read_text().strip() != "1.0":
        raise AssertionError("oracle did not satisfy verifier")
    for name, mutant in mutants().items():
        materialize(target)
        mutant(target, target / "agent_workspace")
        mutant_result = verify(target, reward_dir=rewards / name)
        if mutant_result["reward"] != 0.0 or (rewards / name / "reward.txt").read_text().strip() != "0.0":
            raise AssertionError(f"mutant was accepted: {name}")
    print("LOCA lean CI contract passed: deterministic canary, oracle, NOP, mutants, corpus guard")


if __name__ == "__main__":
    main()
