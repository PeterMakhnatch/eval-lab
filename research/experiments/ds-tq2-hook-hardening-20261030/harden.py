#!/usr/bin/env python3
"""Apply the hardening recipe to COPIES of the packages TQ-1 flags FCI or RES, then re-scan.

Nothing from a package is executed: the copy's `tests/test.sh` is replaced by a generated
version of `hardened-test.sh-template.sh` (same M/CWD/V paths and the package's own reset
list), and TQ-1's published scanner is run over the patched copy.

Usage: /Users/petermakhnatch/Developer/eval-lab/.venv/bin/python harden.py
Writes: results/patched-copy-scan.json
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BRIDGE = Path("/Users/petermakhnatch/Developer/research-context/bridge/2026-10-29-ds-squad/raw")
TQ1 = HERE.parent / "ds-tq1-grader-surface-scan-20261030"
SCANNER = TQ1 / "scan_grader_surface.py"


def _load_scanner():
    import importlib.util

    spec = importlib.util.spec_from_file_location("scan_grader_surface", SCANNER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


decode_build_env = _load_scanner().decode_build_env
TEMPLATE = HERE / "hardened-test.sh-template.sh"
COPIES = Path("/tmp/tq2/copies")
AUTOLOAD_NAMES = [
    "conftest.py",
    "sitecustomize.py",
    "usercustomize.py",
    "pytest.ini",
    "tox.ini",
    "setup.cfg",
]


def scan(pkg: Path) -> dict:
    r = subprocess.run([sys.executable, str(SCANNER), str(pkg)],
                       capture_output=True, text=True, timeout=120)
    if r.returncode != 0:
        return {"error": r.stderr[-500:]}
    return json.loads(r.stdout)


def reset_list_of(test_sh: str) -> list[str]:
    m = re.search(r"<<'EOF_RESET_TEST_FILES'\n(.*?)\nEOF_RESET_TEST_FILES", test_sh, re.S)
    lines = [ln.strip() for ln in (m.group(1).splitlines() if m else []) if ln.strip()]
    return lines


def shell_defaults(test_sh: str) -> dict[str, str]:
    out = {}
    for var in ("M", "CWD", "V"):
        m = re.search(rf"^{var}=(\S+)", test_sh, re.M)
        if m:
            out[var] = m.group(1).strip("'\"")
    return out


def generate(original_test_sh: str, task_id: str, junit_required: int) -> str:
    body = TEMPLATE.read_text()
    names = reset_list_of(original_test_sh)
    for extra in AUTOLOAD_NAMES:
        if extra not in names:
            names.append(extra)
    block = "\n".join(names)
    body = re.sub(r"(<<'EOF_RESET_TEST_FILES'\n).*?(\nEOF_RESET_TEST_FILES)",
                  lambda m: m.group(1) + block + m.group(2), body, count=1, flags=re.S)
    defaults = shell_defaults(original_test_sh)
    header = [f"# generated by ds-tq2-hook-hardening-20261030/harden.py for {task_id}",
              "# original enumerated reset list preserved, auto-load names appended",
              f"JUNIT_REQUIRED={junit_required}"]
    for var, value in defaults.items():
        header.append(f': "${{{var}:={value}}}"')
    body = body.replace("#!/bin/bash\n", "#!/bin/bash\n" + "\n".join(header) + "\n", 1)
    return body


def uses_pytest(pkg: Path, test_sh: str) -> int:
    text = test_sh
    for rel in ("tests/test_command.sh", "tests/test.patch"):
        p = pkg / rel
        if p.is_file():
            patch = p.read_text(errors="replace")
            text += patch
            if rel.endswith("test.patch"):
                text += decode_build_env(patch)
    return int("pytest" in text)


def main() -> int:
    tasks = {}
    for line in (BRIDGE / "SK-2/receipts/tasks.jsonl").read_text().splitlines():
        row = json.loads(line)
        tasks[row["task_id"]] = row["original_task"]
    scan_all = json.loads((BRIDGE / "TQ-1/receipts/scan-all.json").read_text())
    flagged = [r["task_id"] for r in scan_all
               if r["class_flags"]["framework_config_injection"]
               or r["class_flags"]["runner_exit_status_forgery"]]

    COPIES.mkdir(parents=True, exist_ok=True)
    results = {
        "scanner": str(SCANNER),
        "scanner_sha256": subprocess.run(["shasum", "-a", "256", str(SCANNER)],
                                         capture_output=True, text=True).stdout.split()[0],
        "template_sha256": subprocess.run(["shasum", "-a", "256", str(TEMPLATE)],
                                          capture_output=True, text=True).stdout.split()[0],
        "flagged_before": len(flagged),
        "packages": [],
    }
    cleared_fci = cleared_res = both = 0
    for task in sorted(flagged):
        src = Path(tasks[task])
        dst = COPIES / task
        if dst.exists():
            shutil.rmtree(dst, onerror=lambda f, p, e: (os.chmod(p, 0o755), f(p)))
        shutil.copytree(src, dst)
        for root_dir, _dirs, files in os.walk(dst):
            for name in files:
                os.chmod(Path(root_dir) / name, 0o644)
            os.chmod(root_dir, 0o755)
        test_sh = dst / "tests" / "test.sh"
        test_sh.chmod(0o644)
        original = test_sh.read_text()
        before = scan(src)
        test_sh.write_text(generate(original, task, uses_pytest(src, original)))
        after = scan(dst)
        other_before = sorted(k for k, v in before.get("class_flags", {}).items()
                              if k not in ("framework_config_injection", "runner_exit_status_forgery") and v)
        other_after = sorted(k for k, v in after.get("class_flags", {}).items()
                             if k not in ("framework_config_injection", "runner_exit_status_forgery") and v)
        row = {
            "junit_required": uses_pytest(src, original),
            "other_class_flags_changed": other_before != other_after,
            "other_class_flags_before": other_before,
            "other_class_flags_after": other_after,
            "task_id": task,
            "original": str(src),
            "reset_list_before": reset_list_of(original),
            "reset_list_after": reset_list_of(test_sh.read_text()),
            "flags_before": {k: len(v) for k, v in before.get("class_flags", {}).items() if v},
            "flags_after": {k: len(v) for k, v in after.get("class_flags", {}).items() if v},
            "fci_clear": not after["class_flags"]["framework_config_injection"],
            "res_clear": not after["class_flags"]["runner_exit_status_forgery"],
            "has_layer_markers": all(s in test_sh.read_text() for s in
                                     ("reset_autoload", "PYTHONSAFEPATH", "junitxml", "build_fresh")),
            "generated_sha256": subprocess.run(["shasum", "-a", "256", str(test_sh)],
                                               capture_output=True, text=True).stdout.split()[0],
        }
        cleared_fci += row["fci_clear"]
        cleared_res += row["res_clear"]
        both += row["fci_clear"] and row["res_clear"]
        results["packages"].append(row)
        print(task, "FCI", before["class_flags"]["framework_config_injection"] and "flagged" or "-",
              "->", "clear" if row["fci_clear"] else "STILL FLAGGED",
              "| RES ->", "clear" if row["res_clear"] else "STILL FLAGGED", flush=True)

    results["summary"] = {
        "packages": len(flagged),
        "fci_cleared": cleared_fci,
        "res_cleared": cleared_res,
        "both_cleared": both,
        "still_flagged": [p["task_id"] for p in results["packages"]
                          if not (p["fci_clear"] and p["res_clear"])],
        "layer_markers_present": sum(p["has_layer_markers"] for p in results["packages"]),
    }
    out = HERE / "results" / "patched-copy-scan.json"
    out.write_text(json.dumps(results, indent=1, sort_keys=True) + "\n")
    print(json.dumps(results["summary"], indent=1))
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
