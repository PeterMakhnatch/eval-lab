"""HAR-128 G6: join the arm map onto frozen blind metrics and labels (run only after the freeze).

Descriptive only (G6_PLAN.md): per-arm medians/IQR and rates, paired per-task
differences against stock, binary flips, and the list of tasks whose pass/fail
differs between arms. Infra-excluded cells are missing, never zero.

    uv run python research/explorations/trace-lab/har128/g6/g6_compare.py \
        --map ~/Developer/eval-lab/derived/trace-lab/har128-g6/SEALED_arm_map.json \
        --metrics research/explorations/trace-lab/har128/g6/metrics_blind.jsonl \
        --labels research/explorations/trace-lab/har128/g6/labels \
        --out research/explorations/trace-lab/har128/g6/G6_RESULTS_tables.md
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path
from typing import Any

ARMS = ("stock", "tuned", "gepa")
NUMERIC = (
    "agent_steps",
    "tokens_total_proxy",
    "first_edit_step",
    "tokens_after_last_edit_input",
    "turns_after_first_prompt",
    "echo_task_complete_turns",
    "loop_suspicion_score",
    "unparseable",
)
BINARY = (
    "passed",
    "loop_break_fired",
    "loop_break_stopped",
    "loop_onset",
    "handshake_confirmed",
    "never_edited",
    "hit_token_ceiling",
)


def quartiles(values: list[float]) -> str:
    if not values:
        return "—"
    if len(values) == 1:
        return f"{values[0]:g} (n=1)"
    q1, q2, q3 = statistics.quantiles(values, n=4, method="inclusive")
    return f"{q2:g} [{q1:g}–{q3:g}] (n={len(values)})"


def agreed(labels_dir: Path, oid: str, field: str) -> Any:
    a = json.loads((labels_dir / "rater_a" / f"{oid}.json").read_text()).get(field)
    b = json.loads((labels_dir / "rater_b" / f"{oid}.json").read_text()).get(field)
    return a if a == b else "disagree"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--map", type=Path, required=True)
    ap.add_argument("--metrics", type=Path, required=True)
    ap.add_argument("--labels", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    arm_map = json.loads(args.map.read_text())
    rows: dict[tuple[str, str], dict[str, Any]] = {}
    for line in args.metrics.read_text().splitlines():
        r = json.loads(line)
        if r["verdict"] == "excluded":
            continue  # infra: missing, never zero
        r["passed"] = r["verdict"] == "counted_pass"
        r["never_edited"] = r["first_edit_step"] is None
        r["hit_token_ceiling"] = r["stop_reason"] == "ceiling:input_tokens"
        r["arm"] = arm_map[r["id"]]["arm"]
        for f in ("stop_reason", "loop_kind", "blame"):
            r[f"label_{f}"] = agreed(args.labels, r["id"], f)
        rows[(r["task"], r["arm"])] = r
    tasks = sorted({t for t, _ in rows})
    out: list[str] = ["# G6 tables (generated by g6_compare.py after the label freeze)", ""]

    out += ["## Per arm", "", "| metric | " + " | ".join(ARMS) + " |", "|---|---|---|---|"]
    n_row = [str(sum(1 for (_, a) in rows if a == arm)) for arm in ARMS]
    out.append("| scored cells | " + " | ".join(n_row) + " |")
    for m in BINARY:
        cells = []
        for arm in ARMS:
            vals = [r[m] for (_, a), r in rows.items() if a == arm and r[m] is not None]
            cells.append(f"{sum(bool(v) for v in vals)}/{len(vals)}")
        out.append(f"| {m} | " + " | ".join(cells) + " |")
    for m in NUMERIC:
        cells = []
        for arm in ARMS:
            vals = [float(r[m]) for (_, a), r in rows.items() if a == arm and r[m] is not None]
            cells.append(quartiles(vals))
        out.append(f"| {m} (median [IQR]) | " + " | ".join(cells) + " |")
    for f in ("label_stop_reason", "label_loop_kind", "label_blame"):
        for arm in ARMS:
            counts: dict[str, int] = {}
            for (_, a), r in rows.items():
                if a == arm:
                    counts[str(r[f])] = counts.get(str(r[f]), 0) + 1
            out.append(
                f"| {f} · {arm} | "
                + ", ".join(f"{k} {v}" for k, v in sorted(counts.items()))
                + " | | |"
            )

    for arm in ("tuned", "gepa"):
        pairs = [t for t in tasks if (t, "stock") in rows and (t, arm) in rows]
        out += ["", f"## Paired {arm} − stock ({len(pairs)} tasks with both cells)", ""]
        out += ["| metric | median diff [IQR] | flips stock→arm: F→T / T→F |", "|---|---|---|"]
        for m in NUMERIC:
            diffs = [
                float(rows[(t, arm)][m]) - float(rows[(t, "stock")][m])
                for t in pairs
                if rows[(t, arm)][m] is not None and rows[(t, "stock")][m] is not None
            ]
            out.append(f"| {m} | {quartiles(diffs)} | |")
        for m in BINARY:
            up = sum(1 for t in pairs if not rows[(t, "stock")][m] and rows[(t, arm)][m])
            down = sum(1 for t in pairs if rows[(t, "stock")][m] and not rows[(t, arm)][m])
            out.append(f"| {m} | | {up} / {down} |")

    out += [
        "",
        "## Tasks whose pass/fail differs between arms",
        "",
        "| task | " + " | ".join(ARMS) + " |",
        "|---|---|---|---|",
    ]
    for t in tasks:
        res = [rows[(t, a)]["passed"] if (t, a) in rows else None for a in ARMS]
        if len({x for x in res if x is not None}) > 1:
            cell = ["missing" if x is None else ("pass" if x else "fail") for x in res]
            ids = [rows[(t, a)]["id"] if (t, a) in rows else "—" for a in ARMS]
            out.append(
                f"| {t} | "
                + " | ".join(f"{c} ({i})" for c, i in zip(cell, ids, strict=True))
                + " |"
            )
    args.out.write_text("\n".join(out) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
