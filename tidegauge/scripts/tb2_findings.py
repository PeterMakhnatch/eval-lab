"""Write docs/findings/terminal-bench-2-leaderboard.md from the public leaderboard submissions.

Usage:
    scripts/fetch_tb2_leaderboard.sh data/tb2-leaderboard
    uv run python scripts/tb2_findings.py data/tb2-leaderboard > docs/findings/terminal-bench-2-leaderboard.md

Every number in the document comes from this script. It uses only tidegauge's own functions.
"""

from __future__ import annotations

import itertools
import subprocess
import sys
from collections import Counter
from pathlib import Path
from statistics import median

from tidegauge import render, stats
from tidegauge.audit import SEVERITIES, audit
from tidegauge.commands import rank as rank_command
from tidegauge.load import split_arms
from tidegauge.model import Counting

ALPHA = 0.05


def md_table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def main(root: Path) -> None:
    submissions = root / "submissions" / "terminal-bench" / "2.0"
    commit = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True, check=False
    ).stdout.strip()
    arms = split_arms(submissions)
    trials = [t for arm in arms for t in arm.trials]
    every = {arm.name: arm.outcomes(counting=Counting.ALL) for arm in arms}
    scores = {name: stats.score(o) for name, o in every.items()}
    full = [name for name, s in scores.items() if s.attempts_min >= 5]

    out: list[str] = []
    say = out.append
    say("# What the public Terminal-Bench 2.0 leaderboard data can and cannot resolve")
    say("")
    say("Generated by `scripts/tb2_findings.py`. Do not edit by hand.")
    say("")
    say(
        f"- **Data:** `harborframework/terminal-bench-2-leaderboard` on Hugging Face, commit `{commit[:12]}`."
    )
    say(
        f"- **Size:** {len(arms)} submissions, {len(trials):,} trials, {len({t.task for t in trials})} tasks."
    )
    say(
        "- **Counting rule:** every trial counts and a trial without a reward scores 0. This is the leaderboard's rule."
    )
    say(
        "- **Method:** [docs/STATISTICS.md](../STATISTICS.md). No model is used. The rerun test is exact when both "
        "arms have the same number of trials per task."
    )
    say("- These are observations about public files. They do not say why a file is the way it is.")
    say("")

    # 1. Noise
    halves = [(scores[n].ci_rerun().high - scores[n].ci_rerun().low) / 2 for n in full if scores[n].se_rerun]
    floors = [scores[n].noise_floor() for n in full if scores[n].se_rerun]
    task_halves = [(scores[n].ci_tasks().high - scores[n].ci_tasks().low) / 2 for n in full]
    say("## 1. How much does one score move?")
    say("")
    say(f"{len(full)} submissions have 5 or more attempts on every task. For them:")
    say("")
    say(
        md_table(
            ["Quantity", "Median", "Smallest", "Largest"],
            [
                [
                    "Rerun interval, 95% (same tasks again)",
                    *(f"±{100 * f(halves):.1f} pts" for f in (median, min, max)),
                ],
                [
                    "Largest gap between 2 identical runs, 95%",
                    *(f"{100 * f(floors):.1f} pts" for f in (median, min, max)),
                ],
                [
                    "Task interval, 95% (new similar tasks)",
                    *(f"±{100 * f(task_halves):.1f} pts" for f in (median, min, max)),
                ],
            ],
        )
    )
    say("")

    # 2. Ranking
    report = rank_command.build(arms, "reward", Counting.ALL, 0.95, ALPHA)
    widths = [r["rank_interval"][1] - r["rank_interval"][0] + 1 for r in report["arms"]]
    gaps = [r["gap_to_next"] for r in report["arms"] if r["gap_to_next"] is not None]
    say("## 2. Which ranks would survive a rerun?")
    say("")
    say(f"- The median gap between 2 neighbors in the ranking is {100 * median(gaps):.2f} points.")
    say(
        f"- {report['neighbor_pairs_separated']} of {report['neighbor_pairs']} neighbor pairs are separated from "
        f"rerun noise (p < {ALPHA})."
    )
    say(f"- The 95% rank interval of a submission covers {median(widths):.0f} positions (median).")
    say("")
    rows = []
    for r in report["arms"]:
        low, high = r["rank_interval"]
        rows.append(
            [
                r["rank"],
                f"`{r['name']}`",
                render.pct(r["score"]),
                (f"{low} to {high}" if low != high else str(low)) + ("~" if r["noise_borrowed"] else ""),
                "" if r["gap_to_next"] is None else f"{100 * r['gap_to_next']:.1f}",
                {None: "", True: "yes", False: "no"}[r["separated_from_next"]],
            ]
        )
    say(
        md_table(
            ["Rank", "Submission", "Score", "Rank interval, 95%", "Gap to next (pts)", "Separated from next"],
            rows,
        )
    )
    say("")
    say(
        "`~` The submission has 1 attempt per task. Its interval uses the mean trial noise of the other submissions."
    )
    say("")

    # 3. Gap size
    buckets: dict[int, list[int]] = {}
    for a, b in itertools.combinations(every, 2):
        c = stats.compare(every[a], every[b])
        p = c.rerun_p()
        bucket = min(int(abs(c.delta) * 100), 10)
        seen = buckets.setdefault(bucket, [0, 0])
        seen[0] += 1
        seen[1] += int(p is not None and p < ALPHA)
    say("## 3. How large must a gap be?")
    say("")
    say(f"All {sum(v[0] for v in buckets.values()):,} pairs of submissions, by the size of their gap:")
    say("")
    rows = [
        [f"{b} to {b + 1}" if b < 10 else "10 or more", n, hit, f"{100 * hit / n:.0f}%"]
        for b, (n, hit) in sorted(buckets.items())
    ]
    say(md_table(["Gap (points)", "Pairs", "Separated from rerun noise", "Share"], rows))
    say("")

    # 4. Counting rule
    moved = []
    for arm in arms:
        valid = arm.outcomes(counting=Counting.VALID)
        if valid:
            v, a = stats.score(valid).mean, scores[arm.name].mean
            moved.append(
                (abs(v - a), arm.name, v, a, sum(1 for t in arm.trials if not t.valid), len(arm.trials))
            )
    moved.sort(reverse=True)
    say("## 4. How much does the counting rule matter?")
    say("")
    say(
        "Harbor's job mean counts only trials with a valid reward. The leaderboard counts every trial and scores a "
        "missing reward as 0."
    )
    say(
        f"The 2 rules differ by 0.5 points or more for {sum(1 for m in moved if m[0] >= 0.005)} of {len(arms)} "
        f"submissions, and by 1 point or more for {sum(1 for m in moved if m[0] >= 0.01)}."
    )
    say("")
    rows = [
        [f"`{name}`", f"{bad} of {total}", render.pct(v), render.pct(a), f"{100 * gap:.1f}"]
        for gap, name, v, a, bad, total in moved[:12]
    ]
    say(
        md_table(
            [
                "Submission",
                "Trials without a valid reward",
                "Valid trials only",
                "Every trial",
                "Difference (pts)",
            ],
            rows,
        )
    )
    say("")

    # 5. Timeouts
    timeouts = [t for t in trials if t.exception == "AgentTimeoutError"]
    passed = sum(1 for t in timeouts if (t.reward or 0) > 0)
    say("## 5. Timeouts")
    say("")
    say(
        f"{len(timeouts):,} trials ({100 * len(timeouts) / len(trials):.1f}%) end with `AgentTimeoutError`. "
        f"{passed} of them have a reward above 0 and count as passes. Harbor still runs the verifier after an agent "
        "timeout, and the verifier accepted the work."
    )
    say("")

    # 6. Audit
    findings = audit(arms)
    counts = {s: sum(1 for f in findings if f.severity == s) for s in SEVERITIES}
    by_code = Counter((f.severity, f.code) for f in findings)
    say("## 6. Audit")
    say("")
    say(
        f"`tidegauge audit --split` reports {counts['error']} errors, {counts['warn']} warnings and {counts['note']} notes."
    )
    say("")
    rows = [
        [severity, f"`{code}`", n]
        for (severity, code), n in sorted(
            by_code.items(), key=lambda kv: (SEVERITIES.index(kv[0][0]), kv[0][1])
        )
    ]
    say(md_table(["Severity", "Finding", "Count"], rows))
    say("")
    say("Errors and the warnings that are not about counting:")
    say("")
    for f in findings:
        if f.severity == "error" or (f.severity == "warn" and f.code != "invalid-trials"):
            where = f"`{f.arm}`: " if f.arm else ""
            say(f"- **{f.code}** ({f.severity}). {where}{f.message}")
    say("")
    say("## Limits of this document")
    say("")
    say("- The dataset is a snapshot. Submissions closed in May 2026, and the live leaderboard can differ.")
    say(
        "- Scores here use the files as submitted. The leaderboard can disqualify single trials; this document does not."
    )
    say("- A neighbor pair that is not separated is not a tie. The data cannot order it at the 5% level.")
    say(
        "- 74 tests are not corrected for their number. With no real difference, about 4 would be separated by chance."
    )
    say("- The audit reads recorded settings. It cannot see a setting that Harbor did not record.")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]))
