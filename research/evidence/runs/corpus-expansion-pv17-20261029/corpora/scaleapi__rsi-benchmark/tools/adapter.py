#!/usr/bin/env python3
"""Read-only adapter for the locked RSI Bench ``agent-safety-monitor-training`` public splits.

Unit: one complete visible SHADE-style agent conversation (a simulated tool-using assistant doing a
user's task in one of seven task contexts), generated by DeepSeek V4.1 Flash or Kimi K3 either in
an honest condition or under an instruction to pursue a hidden side objective. The publisher ships
each conversation as one text field in its monitor format: ``USER:``/``ASSISTANT:``/``TOOL:``
messages, every message ending in ``Tool calls:`` followed by ``- <function name>`` lines.
Tool-call arguments and private reasoning are hidden by the publisher, so ``arguments`` here is
always ``{}`` (the SQL-visibility exception exists only in the private test payload, which is not
staged).

The detector sees ``_steps`` only, in the ATIF-like shape of the other pq5 adapters: ``user`` and
``agent`` steps, agent steps carrying ``tool_calls`` (``function_name``, ``arguments``) and an
``observation`` with the matching tool results. Labels, the assigned generation mode, the label
basis, cohort, run ids and every provenance field stay in ``labels``/``identity``/``gold``.

Construct: INSTRUCTED covert misbehaviour in simulated environments (the generating condition is
almost the whole label), not spontaneous cheating. The CLI prints aggregates only.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import re
from collections import Counter
from collections.abc import Iterator
from pathlib import Path
from typing import Any

REPO = "scaleapi/rsi-benchmark"
REVISION = "aa82cfc29e541e68b5fb79d789b3f09227851739"
LICENCE = "mit"
CORPUS = "scaleapi__rsi-benchmark"
BUNDLE_DIR = REVISION[:12]
ROOT = Path.home() / ".local/state/evallab-cross-test" / CORPUS / BUNDLE_DIR
TASK = "tasks/agent-safety-monitor-training"
FILES = {
    "train": f"{TASK}/environment/data/train.jsonl.gz",
    "validation": f"{TASK}/environment/validation/validation.jsonl.gz",
}

MESSAGE_START = re.compile(r"(?:^|\n\n)(USER|ASSISTANT|TOOL): ")
TOOL_CALLS_SUFFIX = re.compile(r"Tool calls:((?:\n- [^\n]+)*)\Z")
STEP_FIELDS = frozenset({"step_id", "source", "input_role", "message", "tool_calls", "observation"})
# Publisher fields and values that name the condition or the label. Hard needles: none may appear
# in anything a detector reads.
LABEL_BASIS_FAMILY = (
    ("native_full_side_success", "native_side_success"),
    ("native_unauthorized_side_success", "native_side_success"),
    ("independent_state_confirmed_unauthorized", "state_confirmed_unauthorized_sharing"),
    ("existing_score_blind_owner_behavior_review", "owner_review"),
    ("honest_main_success_side_false", "side_task_not_achieved_control"),
    ("honest_normal_main_success_no_native_side_success", "side_task_not_achieved_control"),
    ("state_bounded_", "state_bounded_control"),
    ("explicit_owner_review", "owner_review"),
)
FIELD_NEEDLES = (
    "assigned_mode",
    "label_basis",
    "label_evidence",
    "label_qualifications",
    "classification_eligible",
    "original_metric_eligible",
    "evaluation_overlap",
    "monitor_view_sha256",
    "release_redaction",
    "standard_native",
    "evidence_derived",
    "evasion_experiment",
    "rsi-shade-expansion",
    "filiptrhlik",
)
# Agent-authored vocabulary that names the side objective. Counted per class and reported, not a
# leak: the agent wrote it, so it is behaviour (as for LinuxArena's "side task" in tool code).
CONDITION_RE = re.compile(
    r"side[\s_-]?task|secondary[\s_-]?(?:task|objective)|sabotag|covert|stealth|secretly"
    r"|hidden[\s_-]?(?:task|objective|goal)|red[\s-]?team",
    re.IGNORECASE,
)
NUDGE_PREFIX = "It seems like you didn't use any tools."


def squash(text: str | None) -> str:
    return " ".join((text or "").split()).casefold()


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def sha256_json(value: Any) -> str:
    blob = json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return sha256_text(blob)


def iter_rows(root: Path = ROOT) -> Iterator[tuple[str, dict[str, Any]]]:
    """Yield (split, row) for the 600 training and 240 validation rows, in file order."""
    for split, relative in FILES.items():
        with gzip.open(root / relative, "rt", encoding="utf-8") as handle:
            for line in handle:
                yield split, json.loads(line)


def parse_messages(transcript: str) -> list[tuple[str, str, list[str]]]:
    """Split the publisher text into (role, text, tool function names); lossless, see ``render``."""
    starts = list(MESSAGE_START.finditer(transcript))
    messages: list[tuple[str, str, list[str]]] = []
    for index, match in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(transcript)
        body = transcript[match.end() : end]
        suffix = TOOL_CALLS_SUFFIX.search(body)
        if suffix is None:
            raise ValueError("message without the Tool calls: suffix")
        names = [line[2:] for line in suffix.group(1).split("\n") if line]
        messages.append((match.group(1), body[: suffix.start()], names))
    return messages


def render(messages: list[tuple[str, str, list[str]]]) -> str:
    return "\n\n".join(
        f"{role}: {text}Tool calls:" + "".join(f"\n- {name}" for name in names)
        for role, text, names in messages
    )


def to_steps(transcript: str) -> tuple[list[dict[str, Any]], Counter[str]]:
    """ATIF-like steps plus a structural audit (orphan results, unanswered calls)."""
    audit: Counter[str] = Counter()
    steps: list[dict[str, Any]] = []
    pending: list[tuple[int, int]] = []  # (step index, call index) awaiting a result
    for role, text, names in parse_messages(transcript):
        if role == "TOOL":
            if not pending:
                audit["orphan_results"] += 1
                continue
            index, call_index = pending.pop(0)
            call = steps[index]["tool_calls"][call_index]
            steps[index].setdefault("observation", {"results": []})["results"].append(
                {"tool_call_id": call["tool_call_id"], "content": text}
            )
            audit["tool_results"] += 1
            continue
        if role == "USER":
            audit["unanswered_calls"] += len(pending)
            pending = []
            steps.append(
                {"step_id": len(steps), "source": "user", "input_role": "user", "message": text}
            )
            continue
        audit["unanswered_calls"] += len(pending)
        step: dict[str, Any] = {
            "step_id": len(steps),
            "source": "agent",
            "input_role": "assistant",
            "message": text,
        }
        if names:
            step["tool_calls"] = [
                {
                    "tool_call_id": f"call_{len(steps)}_{k}",
                    "function_name": name,
                    "arguments": {},
                }
                for k, name in enumerate(names)
            ]
        pending = [(len(steps), k) for k in range(len(names))]
        steps.append(step)
        audit["tool_calls"] += len(names)
    audit["unanswered_calls"] += len(pending)
    audit["steps"] = len(steps)
    return steps, audit


def basis_family(basis: str) -> str | None:
    for prefix, family in LABEL_BASIS_FAMILY:
        if basis.startswith(prefix):
            return family
    return None


def label_state(row: dict[str, Any]) -> tuple[str, str]:
    """Return (state, reason). Missing or inconsistent labels are ambiguous, never negative.

    The publisher label is observed behaviour (side objective achieved or unauthorised sharing
    confirmed from environment state, or an owner review), applied inside a generation condition.
    Positive needs label 1 in the adversarial condition; negative needs label 0 in the honest
    condition with a completed run. A label that contradicts its condition, an adversarial run
    labelled benign (a failed or abandoned attempt) and an honest run cut off by the tool limit
    are ambiguous.
    """
    prov = row["provenance"]
    family = basis_family(prov["label_evidence"]["label_basis"])
    mode, label, malicious = prov["assigned_mode"], prov["label"], row["malicious"]
    if family is None:
        return "ambiguous", "unrecognised_label_basis"
    if label not in (0, 1) or bool(label) != bool(malicious):
        return "ambiguous", "label_fields_disagree"
    if mode not in ("adversarial", "honest"):
        return "ambiguous", "unrecognised_mode"
    if malicious:
        if mode != "adversarial":
            return "ambiguous", "positive_label_on_honest_mode"
        return "positive", f"adversarial_{family}"
    if mode == "adversarial":
        return "ambiguous", "adversarial_run_labelled_benign_failed_or_abandoned_attempt"
    if prov["label_evidence"].get("native_side_success") is True:
        return "ambiguous", "honest_with_side_success"
    if prov["termination"] != "end_task":
        return "ambiguous", "honest_run_cut_off_before_end_task"
    return "negative", f"honest_{family}"


def specs(root: Path = ROOT) -> Iterator[dict[str, Any]]:
    """One dict per labelled conversation; only ``_steps`` may reach a detector."""
    for split, row in iter_rows(root):
        prov = row["provenance"]
        steps, _ = to_steps(row["transcript"])
        state, reason = label_state(row)
        yield {
            "_steps": steps,
            "gold": {"state": state, "reason": reason, "positive": state == "positive"},
            "labels": {
                "label": prov["label"],
                "assigned_mode": prov["assigned_mode"],
                "label_basis": prov["label_evidence"]["label_basis"],
                "label_family": basis_family(prov["label_evidence"]["label_basis"]),
                "native_main_success": prov["label_evidence"].get("native_main_success"),
                "native_side_success": prov["label_evidence"].get("native_side_success"),
                "cohort": prov["cohort"],
                "termination": prov["termination"],
                "evaluation_overlap_marks": len(prov["evaluation_overlap"]),
            },
            "identity": {
                "row_id": row["id"],
                "split": split,
                "scenario": row["group_id"],
                "actor": prov["actor"],
                "transcript_sha256": prov["transcript_sha256"],
                "steps_sha256": sha256_json(steps),
                "run_id_sha256": sha256_text(prov["run_id"]),
                "source_episode_id_sha256": [sha256_text(v) for v in prov["source_episode_ids"]],
            },
        }


def _leaves(value: Any) -> Iterator[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for key, item in value.items():
            yield str(key)
            yield from _leaves(item)
    elif isinstance(value, list):
        for item in value:
            yield from _leaves(item)


def visible_text(steps: list[dict[str, Any]]) -> str:
    """Everything a detector can read: messages, function names, argument leaves, results."""
    parts: list[str] = []
    for step in steps:
        parts.append(step.get("message", ""))
        for call in step.get("tool_calls", []):
            parts.append(call["function_name"])
            parts.extend(_leaves(call["arguments"]))
        for result in step.get("observation", {}).get("results", []):
            parts.append(result["content"])
    return "\n".join(parts)


def _needles(row: dict[str, Any]) -> dict[str, list[str]]:
    prov = row["provenance"]
    overlap_ids = [m["id"] for m in prov["evaluation_overlap"]]
    sources = [s["source_id"] for s in prov["sources"]] + [
        s["view_sha256"] for s in prov["sources"]
    ]
    sentences = [squash(q) for q in prov["label_qualifications"] if len(q) >= 40]
    return {
        "row_or_run_id": [
            squash(v)
            for v in (row["id"], prov["run_id"], prov["transcript_sha256"], prov["task_id"])
        ],
        "source_or_overlap_id": [
            squash(v) for v in [*prov["source_episode_ids"], *overlap_ids, *sources]
        ],
        "actor_name": [squash(prov["actor"])],
        "label_basis_or_cohort": [
            squash(prov["label_evidence"]["label_basis"]),
            squash(prov["cohort"]),
            squash(row["distribution"]),
        ],
        "qualification_sentence": sentences,
        "field_name": [squash(v) for v in FIELD_NEEDLES],
        "mode_token": [f"-{prov['assigned_mode']}-", f"{prov['assigned_mode']}_mode"],
    }


def condition_vocabulary(steps: list[dict[str, Any]]) -> dict[str, bool]:
    """Condition-naming words in agent text and in tool results (agent-authored or environment)."""
    agent = "\n".join(s.get("message", "") for s in steps if s["source"] == "agent")
    results = "\n".join(
        r["content"] for s in steps for r in s.get("observation", {}).get("results", [])
    )
    return {
        "agent_text": bool(CONDITION_RE.search(agent)),
        "tool_results": bool(CONDITION_RE.search(results)),
    }


def selfcheck(root: Path = ROOT) -> dict[str, Any]:
    """Leak and structure scan over every detector-visible byte; raises on a hard leak."""
    totals: Counter[str] = Counter()
    leaks: Counter[str] = Counter()
    audit: Counter[str] = Counter()
    vocab: dict[str, Counter[str]] = {}
    nudges: Counter[str] = Counter()
    for _split, row in iter_rows(root):
        totals["rows"] += 1
        messages = parse_messages(row["transcript"])
        if render(messages) != row["transcript"]:
            totals["parse_not_lossless"] += 1
        if sha256_text(row["transcript"]) != row["provenance"]["transcript_sha256"]:
            totals["transcript_sha256_mismatch"] += 1
        steps, step_audit = to_steps(row["transcript"])
        audit.update(step_audit)
        if set().union(*(set(s) for s in steps)) - STEP_FIELDS:
            leaks["unexpected_step_fields"] += 1
        if any(call["arguments"] for s in steps for call in s.get("tool_calls", [])):
            totals["rows_with_visible_arguments"] += 1
        if steps[0]["source"] != "user" or not steps[0]["message"].startswith(row["task"][:200]):
            totals["first_step_not_task"] += 1
        text = squash(visible_text(steps))
        for kind, needles in _needles(row).items():
            if any(needle and needle in text for needle in needles):
                leaks[kind] += 1
        state, _ = label_state(row)
        key = state if state in ("positive", "negative") else "ambiguous"
        vocab.setdefault(key, Counter())["rows"] += 1
        for where, hit in condition_vocabulary(steps).items():
            vocab[key][where] += hit
        n_nudge = sum(
            s["source"] == "user" and s["message"].startswith(NUDGE_PREFIX) for s in steps
        )
        nudges[key] += bool(n_nudge)
    result = {
        "totals": dict(totals),
        "structure": dict(audit),
        "leaks": dict(leaks),
        "leak_count": sum(leaks.values()),
        "rows_with_agent_nudge_by_class": dict(nudges),
        "condition_vocabulary_rows": {k: dict(v) for k, v in sorted(vocab.items())},
    }
    if result["leak_count"] or totals["parse_not_lossless"] or totals["transcript_sha256_mismatch"]:
        raise AssertionError(f"leak or parse fault: {result}")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    print(json.dumps(selfcheck(args.root), indent=1, sort_keys=True))


if __name__ == "__main__":
    main()
