#!/bin/bash
# Morning Briefing — eval-lab overnight activity summary
# Runs at 08:00 ET daily via launchd (com.evellab.morning-briefing.plist).
# Writes digest, sends macOS notification, renames Herdr tab on success.

set -eu
REPO="/Users/petermakhnatch/Developer/eval-lab"
TODAY=$(date +%Y-%m-%d)
OUT="$REPO/digests/${TODAY}-morning-briefing.md"
SINCE_HOURS=12
cd "$REPO"

{
  echo "# ☀️ Morning Briefing — ${TODAY}"
  echo ""
  echo "_Auto-generated at $(date '+%H:%M:%S %Z'). Covers the last ${SINCE_HOURS} hours + last night's automation._"
  echo ""

  # ── 1. Nightly automation digest ─────────────────────────────────────────
  echo "## 1. Overnight Automation (nightly digest)"
  echo ""
  NIGHTLY="$REPO/digests/${TODAY}.md"
  if [ -f "$NIGHTLY" ]; then
    echo "- Nightly digest: \`digests/${TODAY}.md\` ($(wc -l < "$NIGHTLY" | tr -d ' ') lines)"
    # Extract verdict lines
    grep -m1 "VERDICT:" "$NIGHTLY" 2>/dev/null | sed 's/^/  - /' || true
    echo "  - Dispatches this cycle: $(grep -m1 'Dispatches in this nightly cycle' "$NIGHTLY" | awk '{print $NF}')"
    echo "  - Quarantined: $(grep -m1 'Quarantined:' "$NIGHTLY" | awk '{print $NF}')"
  else
    echo "- ⚠️ No nightly digest found for today."
  fi
  echo ""

  # ── 2. Git activity ──────────────────────────────────────────────────────
  echo "## 2. Git Activity (last ${SINCE_HOURS}h)"
  echo ""
  MERGES=$(git log --all --oneline --since="${SINCE_HOURS} hours ago" 2>/dev/null | wc -l | tr -d ' ')
  echo "- Total commits: **${MERGES}**"
  echo ""
  if [ "$MERGES" -gt 0 ]; then
    echo '```'
    git log --all --oneline --since="${SINCE_HOURS} hours ago" 2>/dev/null | head -20
    if [ "$MERGES" -gt 20 ]; then echo "... and $((MERGES - 20)) more"; fi
    echo '```'
  fi
  echo ""

  # ── 3. Queue events (since midnight UTC) ─────────────────────────────────
  echo "## 3. Queue & Policy Events (since midnight)"
  echo ""
  if [ -f queue/events.jsonl ]; then
    MIDNIGHT=$(date -u +%Y-%m-%dT00:00:00)
    EVENTS=$(python3 -c "
import json, sys
counts = {}
waiting = []
with open('queue/events.jsonl') as f:
    for line in f:
        try:
            e = json.loads(line)
            if e.get('occurred_at','') >= '${MIDNIGHT}':
                ev = e.get('event','?')
                counts[ev] = counts.get(ev, 0) + 1
                if ev in ('policy_waiting','submitted') and e.get('job_name'):
                    waiting.append(f\"  - [{ev}] {e['job_name']}\")
        except: pass
for k,v in sorted(counts.items()):
    print(f'  - {k}: {v}')
print()
if waiting:
    print('  **Waiting for your approval:**')
    for w in waiting[:10]: print(w)
" 2>/dev/null || echo "  (parse error)")
    echo "$EVENTS"
  fi
  echo ""

  # ── 4. New runs ──────────────────────────────────────────────────────────
  echo "## 4. New Trial Runs (last ${SINCE_HOURS}h)"
  echo ""
  NEW_RUNS=$(find runs -maxdepth 1 -type d -mmin -$((SINCE_HOURS * 60)) 2>/dev/null | tail -n +2 | wc -l | tr -d ' ')
  echo "- New run directories: **${NEW_RUNS}**"
  if [ "$NEW_RUNS" -gt 0 ]; then
    find runs -maxdepth 1 -type d -mmin -$((SINCE_HOURS * 60)) 2>/dev/null | tail -n +2 | sort | while read d; do
      echo "  - $(basename "$d") ($(stat -f '%Sm' -t '%H:%M' "$d"))"
    done
  fi
  echo ""

  # ── 5. Action items ──────────────────────────────────────────────────────
  echo "## 5. ⚡ Needs Your Attention"
  echo ""
  PENDING=$(ls queue/waiting/ 2>/dev/null | wc -l | tr -d ' ')
  PROPOSED=$(ls queue/proposed/ 2>/dev/null | wc -l | tr -d ' ')
  echo "- Specs waiting for approval: **${PENDING}**"
  echo "- Specs proposed: ${PROPOSED}"
  if [ "$PENDING" -gt 0 ]; then
    echo ""
    echo "Approve with: \`uv run evallab approve <spec-id> --actor peter\`"
    ls queue/waiting/ 2>/dev/null | head -8 | sed 's/^/  - /'
  fi
  echo ""

  # ── 6. Roster sync check ─────────────────────────────────────────────────
  echo "## 6. 🎯 Eval Roster Sync"
  echo ""
  echo '```'
  (cd "$REPO" && uv run python -m evallab.roster 2>/dev/null) || echo "  (roster check failed — run: uv run python -m evallab.roster)"
  echo '```'
  echo ""
  echo "---"
  echo "_Generated by scripts/morning-briefing.sh via launchd at 08:00 ET._"
} > "$OUT"

# ── Signal completion: macOS notification ──────────────────────────────────
osascript -e "display notification \"Morning briefing ready: ${TODAY}. ${MERGES:-0} commits, ${NEW_RUNS:-0} new runs, ${PENDING:-0} awaiting approval.\" with title \"☀️ Eval-Lab Morning Briefing\" sound name \"Glass\"" 2>/dev/null || true

# ── Signal completion: Herdr tab label (best-effort) ───────────────────────
if command -v herdr >/dev/null 2>&1; then
  herdr tab rename wH:t5 "🟣 Researcher — 📋 Briefing ${TODAY}" 2>/dev/null || true
fi

echo "$OUT"
